/// Режимы работы NSky.
///
/// Продукт один, но ролей две (согласовано с заказчиком):
///
///  * **Клиент** — сотрудник. Главный экран: одна кнопка, статус, скорость.
///    Никаких настроек, профилей на редактирование, диагностики. Всё, что нужно,
///    приходит из подписки, которую выдаёт администратор.
///
///  * **Админ** — ИТ-специалист (их двое). Тот же клиент, но в меню появляются
///    профили, серверы, журналы и инструменты. Так не нужно писать и
///    сопровождать два отдельных приложения.
///
/// Переключение — в настройках, закрыто PIN-кодом. PIN хранится в настройках
/// приложения, а не в коде: администратор задаёт его сам при первом включении
/// админ-режима.
library;

import 'dart:async';

import 'package:flutter/foundation.dart';

enum NskyRole {
  /// Сотрудник: минимум на экране, ничего не настраивает.
  client,

  /// Администратор: видит диагностику и управление профилями.
  admin,
}

/// Состояние режима. Намеренно простое и локальное: серверная часть
/// (панель Remnawave) сама решает, кому какие подписки доступны.
class NskyMode {
  const NskyMode._();

  /// Значение PIN по умолчанию пустое: пока администратор не задал свой,
  /// включить админ-режим нельзя (защита от случайного нажатия сотрудником).
  static const defaultAdminPin = '';

  static bool isAdmin(FutureOr<String> pin, String entered) {
    if (pin is String) {
      return pin.isNotEmpty && pin == entered;
    }
    return false;
  }
}

